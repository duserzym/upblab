import { afterEach, beforeEach, expect, it, vi } from 'vitest';
vi.mock('./identity.svelte', () => ({ identity: { target: { server: 'https://lab' }, revision: 0, signedIn: true, get: vi.fn() } }));
vi.mock('./atlas-refresh', () => ({ observe: vi.fn(), refreshAtlasMount: vi.fn(async () => {}), readAtlasProject: vi.fn() }));
vi.mock('./overview.svelte', () => ({ overview: { refreshSession: vi.fn(async () => {}) } }));
vi.mock('./review.svelte', () => ({ review: { scope: { kind: 'session', id: 's' }, rows: [], load: vi.fn(async () => {}) } }));
const { appWatch } = await import('./app-watch.svelte');
const { identity } = await import('./identity.svelte');
const { observe, refreshAtlasMount, readAtlasProject } = await import('./atlas-refresh');
const { overview } = await import('./overview.svelte');
const { review } = await import('./review.svelte');
const project = { status: 200, body: { revision: 1, mount_id: 'm', atlas_version: 1 } };
async function settle() { await vi.advanceTimersByTimeAsync(0); }
beforeEach(() => {
  vi.useFakeTimers(); vi.setSystemTime(0); vi.clearAllMocks(); appWatch.clear();
  vi.stubGlobal('document', { visibilityState: 'visible' });
  identity.revision++; (identity as { signedIn: boolean }).signedIn = true;
  review.scope = { kind: 'session', id: 's', run: 'preferred' }; review.rows = [];
  vi.mocked(readAtlasProject).mockResolvedValue(project);
  vi.mocked(observe).mockReturnValue(null);
  vi.mocked(identity.get).mockResolvedValue({ status: 200, body: [] });
});
afterEach(() => { appWatch.clear(); vi.useRealTimers(); vi.unstubAllGlobals(); });
it('polls visible projects, refreshes revisions without requiring v4 and skips unchanged content', async () => {
  appWatch.atlas('p', 'm'); await settle();
  expect(readAtlasProject).toHaveBeenCalledTimes(1);
  expect(refreshAtlasMount).not.toHaveBeenCalled();
  vi.mocked(observe).mockReturnValueOnce('content');
  await vi.advanceTimersByTimeAsync(20_000);
  expect(refreshAtlasMount).toHaveBeenCalledWith('m', true);
  expect(readAtlasProject).toHaveBeenCalledTimes(2);
  Object.assign(document, { visibilityState: 'hidden' });
  await vi.advanceTimersByTimeAsync(20_000);
  expect(readAtlasProject).toHaveBeenCalledTimes(2);
  Object.assign(document, { visibilityState: 'visible' });
  await appWatch.check();
  expect(readAtlasProject).toHaveBeenCalledTimes(3);
});
it('allows at most one in-flight request per watched object and backs errors off ten minutes', async () => {
  let finish!: (value: typeof project) => void;
  vi.mocked(readAtlasProject).mockImplementationOnce(() => new Promise(resolve => { finish = resolve; }));
  appWatch.atlas('p', 'm');
  await appWatch.check();
  await vi.advanceTimersByTimeAsync(20_000);
  expect(readAtlasProject).toHaveBeenCalledTimes(1);
  finish({ status: 503, body: project.body }); await settle();
  await vi.advanceTimersByTimeAsync(580_000);
  expect(readAtlasProject).toHaveBeenCalledTimes(1);
  await vi.advanceTimersByTimeAsync(20_000);
  expect(readAtlasProject).toHaveBeenCalledTimes(2);
});
it('discovers new session run ids, refreshes matching Review and keeps unrelated scopes alone', async () => {
  appWatch.session('s'); await settle();
  vi.clearAllMocks();
  await appWatch.check();
  expect(overview.refreshSession).not.toHaveBeenCalled();
  vi.mocked(identity.get).mockResolvedValue({ status: 200, body: [{ id: 'r1' }] });
  await appWatch.check();
  expect(overview.refreshSession).toHaveBeenCalledWith('s');
  expect(review.load).toHaveBeenCalledWith({ quiet: true });
  vi.clearAllMocks();
  review.scope = { kind: 'mount', id: 'm' };
  review.rows = [{ sessionId: 's' }] as typeof review.rows;
  vi.mocked(identity.get).mockResolvedValue({ status: 200, body: [{ id: 'r1' }, { id: 'r2' }] });
  await appWatch.check();
  expect(review.load).toHaveBeenCalledTimes(1);
  vi.clearAllMocks(); review.rows = [];
  vi.mocked(identity.get).mockResolvedValue({ status: 200, body: [{ id: 'r3' }] });
  await appWatch.check();
  expect(overview.refreshSession).toHaveBeenCalledTimes(1);
  expect(review.load).not.toHaveBeenCalled();
});
it('expires two hours after the last opener, stopping its timer', async () => {
  appWatch.session('s'); await settle();
  await vi.advanceTimersByTimeAsync(60 * 60_000);
  appWatch.session('s');
  await vi.advanceTimersByTimeAsync(60 * 60_000);
  expect(appWatch.size).toBe(1);
  await vi.advanceTimersByTimeAsync(60 * 60_000);
  expect(appWatch.size).toBe(0);
  expect(vi.getTimerCount()).toBe(0);
});
it('clears watches and ignores old replies on identity source changes', async () => {
  let finish!: (value: typeof project) => void;
  vi.mocked(readAtlasProject).mockImplementationOnce(() => new Promise(resolve => { finish = resolve; }));
  appWatch.atlas('p', 'm');
  identity.revision++; appWatch.syncSource();
  finish(project); await settle();
  expect(appWatch.size).toBe(0);
  expect(observe).not.toHaveBeenCalled();
  expect(refreshAtlasMount).not.toHaveBeenCalled();
  expect(vi.getTimerCount()).toBe(0);
});
